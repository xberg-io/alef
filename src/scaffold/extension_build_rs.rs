//! `build.rs` for the extension-module binding crates whose cdylib leaves host C-API symbols
//! undefined until the interpreter loads it: pyo3 (Python), ext-php-rs (PHP) and magnus/rb-sys
//! (Ruby). macOS ld64 rejects those symbols at link time unless the cdylib is linked with
//! `-undefined dynamic_lookup`.
//!
//! The flag goes to that crate's cdylib, tests, benches and examples via the per-kind
//! `cargo:rustc-link-arg-{cdylib,tests,benches,examples}` directives, instead of a workspace-wide
//! `[target.'cfg(target_os = "macos")'] rustflags` entry. That entry also reached every shipped
//! executable, forcing ld64 off chained fixups and turning link errors into runtime crashes.
//! `[[bin]]` targets never get it. Test, bench and example executables keep the reach the old
//! entry gave them, so `cargo test --all-targets` still links on macOS.
//!
//! A crate whose `[package_metadata.cargo] include` list is set must list `build.rs`, or the
//! packaged crate ships without the flag.
//!
//! Backends not handled here get the flag elsewhere or do not need it. `napi_build::setup()`
//! emits it for Node. Rustler resolves NIF symbols dynamically since 0.36. The Swift crate's own
//! build script passes `-U` per Swift export. FFI, JNI, Dart, Go, Java, C#, Zig and WASM cdylibs
//! reference no host symbols, and the R crate is a staticlib linked by R's own toolchain. ~keep

use std::path::{Path, PathBuf};

use crate::core::backend::GeneratedFile;
use crate::core::config::{Language, ResolvedCrateConfig};

/// The linker argument the generated build script passes on macOS targets.
const MACOS_DYNAMIC_LOOKUP_LINK_ARG: &str = "-Wl,-undefined,dynamic_lookup";

/// Target kinds that receive the link argument. `bins` is absent on purpose: shipped executables
/// must keep ld64's defaults.
const LINK_ARG_TARGET_KINDS: &[&str] = &["cdylib", "tests", "benches", "examples"];

/// Directive names a hand-written build script can use to pass the flag to its cdylib; the second
/// is cargo's legacy spelling.
const CDYLIB_LINK_ARG_DIRECTIVES: &[&str] = &["rustc-link-arg-cdylib", "rustc-cdylib-link-arg"];

/// One `build.rs` per extension-module binding crate among `languages`.
///
/// A `build.rs` already on disk without an alef marker belongs to the user: it is left alone
/// (the scaffold writer would refuse it anyway) and, unless it already passes `dynamic_lookup`
/// to its cdylib, a warning names the line to add.
pub(crate) fn extension_build_scripts(config: &ResolvedCrateConfig, languages: &[Language]) -> Vec<GeneratedFile> {
    languages
        .iter()
        .filter_map(|&lang| extension_crate_dir(config, lang))
        .filter_map(|crate_dir| build_script_for(config, &crate_dir))
        .collect()
}

/// Workspace-relative directory of `lang`'s binding crate when its cdylib needs host symbols
/// resolved at load time.
fn extension_crate_dir(config: &ResolvedCrateConfig, lang: Language) -> Option<PathBuf> {
    let core_crate_dir = config.core_crate_dir();
    match lang {
        Language::Python => Some(PathBuf::from(format!("crates/{core_crate_dir}-py"))),
        Language::Php => Some(PathBuf::from(format!("crates/{core_crate_dir}-php"))),
        Language::Ruby => crate::scaffold::ruby_native_manifest_path(config)
            .parent()
            .map(Path::to_path_buf),
        _ => None,
    }
}

fn build_script_for(config: &ResolvedCrateConfig, crate_dir: &Path) -> Option<GeneratedFile> {
    let path = crate_dir.join("build.rs");
    let existing = config
        .workspace_root
        .as_deref()
        .map(|root| root.join(&path))
        .and_then(|on_disk| std::fs::read_to_string(&on_disk).ok().map(|text| (on_disk, text)));
    if let Some((on_disk, existing)) = existing
        && !crate::core::hash::content_has_alef_marker(&existing)
    {
        if !passes_cdylib_dynamic_lookup(&existing) {
            tracing::warn!(
                "{} is not generated by alef, so alef will not add its macOS link flag: add \
                 `if std::env::var(\"CARGO_CFG_TARGET_OS\").as_deref() == Ok(\"macos\") {{ \
                 println!(\"cargo:rustc-link-arg-cdylib={MACOS_DYNAMIC_LOOKUP_LINK_ARG}\"); }}` \
                 to its main(), or the cdylib fails to link on macOS now that \
                 .cargo/config.toml no longer sets -undefined dynamic_lookup workspace-wide",
                on_disk.display()
            );
        }
        return None;
    }
    Some(GeneratedFile {
        path,
        content: build_script_content(),
        generated_header: true,
    })
}

fn passes_cdylib_dynamic_lookup(build_rs: &str) -> bool {
    build_rs.lines().any(|line| {
        !line.trim_start().starts_with("//")
            && line.contains("dynamic_lookup")
            && CDYLIB_LINK_ARG_DIRECTIVES
                .iter()
                .any(|directive| line.contains(directive))
    })
}

fn build_script_content() -> String {
    let directives: String = LINK_ARG_TARGET_KINDS
        .iter()
        .map(|kind| format!("        println!(\"cargo:rustc-link-arg-{kind}={MACOS_DYNAMIC_LOOKUP_LINK_ARG}\");\n"))
        .collect();
    format!(
        r#"fn main() {{
    println!("cargo:rerun-if-changed=build.rs");
    // The host interpreter supplies its C-API symbols when it loads this extension.
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("macos") {{
{directives}    }}
}}
"#
    )
}
