use super::*;
use tracing_test::traced_test;

const DIRECTIVE: &str = "cargo:rustc-link-arg=-Wl,-undefined,dynamic_lookup";
const EXPECTED_BUILD_RS: &str = r#"fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    // The host interpreter supplies its C-API symbols when it loads this extension.
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("macos") {
        println!("cargo:rustc-link-arg=-Wl,-undefined,dynamic_lookup");
    }
}
"#;

fn build_scripts(files: &[GeneratedFile]) -> Vec<&GeneratedFile> {
    files.iter().filter(|f| f.path.ends_with("build.rs")).collect()
}

fn assert_macos_build_script(file: &GeneratedFile) {
    assert!(file.generated_header, "{} must be alef-owned", file.path.display());
    syn::parse_file(&file.content).expect("generated build.rs must be valid Rust");
    assert_eq!(file.content, EXPECTED_BUILD_RS);
    // Cargo rejects the per-kind link directives for a package without a target of that kind,
    // so only the plain form, valid for every target kind, may be emitted.
    for kind in ["tests", "benches", "examples", "bins", "bin", "cdylib"] {
        assert!(
            !file.content.contains(&format!("rustc-link-arg-{kind}")),
            "per-kind directive `{kind}` would fail on a crate lacking that target:\n{}",
            file.content
        );
    }
}

#[test]
fn python_php_and_ruby_scaffolds_emit_an_exact_macos_build_script() {
    let api = test_api();
    let config = test_config();
    for (lang, expected) in [
        (Language::Python, "crates/my-lib-py/build.rs"),
        (Language::Php, "crates/my-lib-php/build.rs"),
        (Language::Ruby, "packages/ruby/ext/my_lib_rb/native/build.rs"),
    ] {
        let files = scaffold(&api, &config, &[lang]).unwrap();
        let scripts = build_scripts(&files);
        assert_eq!(scripts.len(), 1, "{lang:?}: {scripts:?}");
        assert_eq!(scripts[0].path, PathBuf::from(expected), "{lang:?}");
        assert_macos_build_script(scripts[0]);
    }
}

#[test]
fn backends_whose_toolchain_or_runtime_covers_host_symbols_get_no_build_script() {
    let api = test_api();
    let config = test_config();
    for lang in [Language::Node, Language::Elixir, Language::Jni, Language::Ffi] {
        let files = scaffold(&api, &config, &[lang]).unwrap();
        assert!(
            build_scripts(&files).is_empty(),
            "{lang:?} must not get a dynamic_lookup build.rs: {:?}",
            build_scripts(&files)
        );
    }
}

#[test]
#[traced_test]
fn a_hand_written_build_script_is_left_alone_and_the_missing_line_is_reported() {
    let dir = tempfile::tempdir().unwrap();
    let crate_dir = dir.path().join("crates/my-lib-php");
    std::fs::create_dir_all(&crate_dir).unwrap();
    std::fs::write(crate_dir.join("build.rs"), "fn main() {}\n").unwrap();
    let mut config = test_config();
    config.workspace_root = Some(dir.path().to_path_buf());

    let files = scaffold(&test_api(), &config, &[Language::Php]).unwrap();

    assert!(build_scripts(&files).is_empty(), "{:?}", build_scripts(&files));
    assert!(logs_contain("is not generated by alef"));
    assert!(logs_contain(DIRECTIVE));
}

