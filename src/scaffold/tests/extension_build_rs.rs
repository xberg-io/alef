#[test]
fn a_hand_written_node_build_script_gets_no_dynamic_lookup_build_script() {
    let dir = tempfile::tempdir().unwrap();
    let crate_dir = dir.path().join("crates/my-lib-node");
    std::fs::create_dir_all(&crate_dir).unwrap();
    std::fs::write(crate_dir.join("build.rs"), "fn main() { napi_build::setup(); }\n").unwrap();
    let mut config = test_config();
    config.workspace_root = Some(dir.path().to_path_buf());

    let files = scaffold(&test_api(), &config, &[Language::Node]).unwrap();

    assert!(build_scripts(&files).is_empty(), "{:?}", build_scripts(&files));
    let manifest = files
        .iter()
        .find(|f| f.path == Path::new("crates/my-lib-node/Cargo.toml"))
        .expect("node binding manifest");
    assert!(
        manifest.content.contains("[build-dependencies]\nnapi-build = "),
        "an existing node build.rs must still get napi-build:\n{}",
        manifest.content
    );
}

/// A binding crate with a cdylib and no test, bench or example target must still build with the
/// generated script. On a macOS host this runs the gated branch, where cargo rejects
/// `rustc-link-arg-tests` for a package without a test target.
#[test]
fn generated_build_script_compiles_in_a_cdylib_crate_without_a_test_target() {
    let files = scaffold(&test_api(), &test_config(), &[Language::Php]).unwrap();
    let script = build_scripts(&files)[0];
    let dir = tempfile::tempdir().unwrap();
    std::fs::create_dir(dir.path().join("src")).unwrap();
    std::fs::write(
        dir.path().join("src/lib.rs"),
        "#[unsafe(no_mangle)]\npub extern \"C\" fn probe() {}\n",
    )
    .unwrap();
    std::fs::write(dir.path().join("build.rs"), &script.content).unwrap();
    std::fs::write(
        dir.path().join("Cargo.toml"),
        "[package]\nname = \"extension-build-rs-probe\"\nversion = \"0.0.0\"\nedition = \"2024\"\n\
         [lib]\ncrate-type = [\"cdylib\"]\n",
    )
    .unwrap();

    let build = std::process::Command::new(std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into()))
        .args(["build", "--offline"])
        .current_dir(dir.path())
        .env("CARGO_TARGET_DIR", dir.path().join("target"))
        .output()
        .unwrap();

    assert!(
        build.status.success(),
        "stderr:\n{}",
        String::from_utf8_lossy(&build.stderr)
    );
}
