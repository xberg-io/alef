//! A components-only crate relocks `Cargo.lock` exactly when a producer manifest it generated was
//! rewritten, and never touches the workspace members it does not own. The workspace is path-only
//! so `cargo update --offline -w` needs no registry.

use super::*;
use crate::core::config::NewAlefConfig;
use crate::test_support::{CwdGuard, git_add, git_init, write_file};

const VENDORED_MANIFEST: &str = "[package]\nname = \"vendored\"\nversion = \"0.8.0\"\nedition = \"2024\"\n\n[dependencies]\ndemo = { path = \"../demo\" }\n";
const PRODUCER_MANIFEST: &str = "# This file is auto-generated by alef\n[package]\nname = \"demo-pdf-component\"\nversion = \"1.2.0\"\nedition = \"2024\"\npublish = false\n\n[dependencies]\ndemo = { path = \"../../crates/demo\", version = \"1.2.0\" }\n";

fn lock_version(root: &std::path::Path, package: &str) -> String {
    let lock: toml::Value = toml::from_str(&std::fs::read_to_string(root.join("Cargo.lock")).unwrap()).unwrap();
    lock["package"]
        .as_array()
        .unwrap()
        .iter()
        .find(|entry| entry["name"].as_str() == Some(package))
        .unwrap_or_else(|| panic!("{package} missing from Cargo.lock"))["version"]
        .as_str()
        .unwrap()
        .to_string()
}

fn fixture(root: &std::path::Path) -> (crate::core::config::ResolvedCrateConfig, std::path::PathBuf) {
    git_init(root);
    write_file(
        root,
        "Cargo.toml",
        "[workspace]\nresolver = \"2\"\nmembers = [\"crates/demo\", \"crates/vendored\", \"producers/pdf\"]\n",
    );
    write_file(
        root,
        "crates/demo/Cargo.toml",
        "[package]\nname = \"demo\"\nversion = \"1.2.0\"\nedition = \"2024\"\n",
    );
    write_file(root, "crates/vendored/Cargo.toml", VENDORED_MANIFEST);
    write_file(root, "producers/pdf/Cargo.toml", PRODUCER_MANIFEST);
    for lib in ["crates/demo", "crates/vendored", "producers/pdf"] {
        write_file(root, &format!("{lib}/src/lib.rs"), "");
    }
    let alef_toml = r#"[workspace]

[[crates]]
name = "demo"
sources = []
version_from = "crates/demo/Cargo.toml"

[[crates.component_contracts]]
name = "extractor"
trait_path = "demo::Extractor"
interface_version = 1

[[crates.components]]
name = "pdf"
provides = [{ contract = "extractor", implementation = "demo::PdfExtractor" }]
features = ["pdf"]
default_features = false
targets = ["x86_64-unknown-linux-gnu"]
producer_dir = "producers/pdf"
"#;
    let config_path = write_file(root, "alef.toml", alef_toml);
    let status = std::process::Command::new("cargo")
        .args(["generate-lockfile", "--offline"])
        .current_dir(root)
        .status()
        .expect("run cargo generate-lockfile");
    assert!(status.success(), "a path-only workspace must lock offline");
    git_add(
        root,
        &[
            "Cargo.toml",
            "Cargo.lock",
            "alef.toml",
            "crates/demo/Cargo.toml",
            "crates/demo/src/lib.rs",
            "crates/vendored/Cargo.toml",
            "crates/vendored/src/lib.rs",
            "producers/pdf/Cargo.toml",
            "producers/pdf/src/lib.rs",
        ],
    );
    let parsed: NewAlefConfig = toml::from_str(alef_toml).expect("parse alef.toml");
    (parsed.resolve().expect("resolve config").remove(0), config_path)
}

#[test]
fn version_bump_relocks_the_producer_and_leaves_the_vendored_member_untouched() {
    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path().canonicalize().unwrap();
    let (config, config_path) = fixture(&root);
    assert_eq!(lock_version(&root, "demo-pdf-component"), "1.2.0");

    {
        let _cwd = CwdGuard::enter(&root);
        sync_versions(&config, &config_path, Some("patch"), true, true, None).expect("sync_versions ok");
    }

    let producer = std::fs::read_to_string(root.join("producers/pdf/Cargo.toml")).unwrap();
    assert!(
        producer.contains("version = \"1.2.1\""),
        "producer must be stamped:\n{producer}"
    );
    assert_eq!(
        lock_version(&root, "demo-pdf-component"),
        "1.2.1",
        "producer lock entry must be relocked"
    );
    assert_eq!(lock_version(&root, "vendored"), "0.8.0");
    assert_eq!(
        std::fs::read_to_string(root.join("crates/vendored/Cargo.toml")).unwrap(),
        VENDORED_MANIFEST,
        "a member alef does not own must not be rewritten"
    );
}

#[test]
fn no_producer_change_means_no_relock() {
    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path().canonicalize().unwrap();
    let (config, config_path) = fixture(&root);
    let stale = std::fs::read_to_string(root.join("Cargo.lock"))
        .unwrap()
        .replace("version = \"0.8.0\"", "version = \"0.7.0\"");
    std::fs::write(root.join("Cargo.lock"), &stale).unwrap();

    {
        let _cwd = CwdGuard::enter(&root);
        sync_versions(&config, &config_path, None, true, true, None).expect("sync_versions ok");
    }

    assert_eq!(
        std::fs::read_to_string(root.join("Cargo.lock")).unwrap(),
        stale,
        "nothing alef owns changed, so the lock must not be relocked"
    );
}
