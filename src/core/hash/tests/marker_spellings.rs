//! Enumeration of every marker spelling alef's emitters actually produce.
//!
//! Two sources, both derived from real emitters rather than hand-copied prose so this list can't
//! silently drift from what alef actually ships:
//!
//! - Rust-side literals that have been hoisted into named constants in [`crate::core::hash`]
//!   (`STANDARD_HEADER_LINE`, `SWIFT_C_UMBRELLA_HEADER_MARKER`, `CITATION_CFF_HEADER_LINE`,
//!   `SELF_MARKING_HEADER_LINE`) because at least one call site duplicated the literal, or the
//!   brief's confirmed example lived here. Every production call site listed in each constant's
//!   doc comment now reads the same constant, so a spelling change only has to compile once.
//! - `.jinja` templates that bake their own header line directly into the template file instead
//!   of going through [`crate::core::hash::header`]/[`crate::core::hash::header_for_config`].
//!   These are pulled in with `include_str!`, which embeds the exact bytes of the template file
//!   at compile time -- if a template's header line is ever edited, this list sees the new text
//!   automatically, and [`super::every_known_marker_spelling_is_recognized`] re-checks it. This
//!   can only go stale by omission (a brand-new template not yet added below), not by drift of an
//!   already-listed one.
//!
//! Deliberately built as two separate slices (constants can't hold a computed concatenation of
//! `include_str!` calls without repeating each entry's index by hand, which is exactly the kind
//! of hand-maintained list this module exists to avoid) and chained at iteration time by
//! [`all_known_marker_texts`]. ~keep

