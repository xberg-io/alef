/// Every marker spelling this crate is known to emit: [`RUST_CONSTANT_MARKERS`] chained with
/// [`SELF_MARKING_TEMPLATES`]. See the module doc for how this stays derived from real emitters
/// instead of hand-copied prose. ~keep
pub(crate) fn all_known_marker_texts() -> impl Iterator<Item = &'static str> {
    RUST_CONSTANT_MARKERS.iter().chain(SELF_MARKING_TEMPLATES).copied()
}

#[test]
fn self_marking_templates_enumeration_is_non_empty() {
    // A cheap tripwire against an accidental empty list (e.g. every entry removed by mistake),
    // which would make `every_known_marker_spelling_is_recognized` vacuously pass. Exact counts
    // deliberately aren't asserted here -- the list is expected to grow as backends are added.
    assert!(!RUST_CONSTANT_MARKERS.is_empty());
    assert!(!SELF_MARKING_TEMPLATES.is_empty());
    assert_eq!(
        all_known_marker_texts().count(),
        RUST_CONSTANT_MARKERS.len() + SELF_MARKING_TEMPLATES.len()
    );
}

/// The enumeration above can only go stale one way: by omission. A brand-new self-marking
/// template is not in [`SELF_MARKING_TEMPLATES`], so nothing checks its spelling, and the file it
/// stamps is refused on every run forever with no diagnostic -- which is the exact defect this
/// module was written to close, reappearing one template later.
///
/// So don't maintain the list: walk the shipped templates and ask each one directly. A template
/// fails here if it clearly *intends* to stamp provenance -- its text says something was
/// "generated by" and names alef -- yet [`content_has_alef_marker`] would still refuse the result,
/// whether or not anyone remembered to add it to the list above.
///
/// The intent test is deliberately narrower than [`near_miss_marker`], which the runtime refusal
/// uses. That one fires on any leading line mentioning alef and "generated" independently, which
/// is right for a diagnostic on a file already being refused -- a false positive there costs one
/// extra hint -- but wrong as a build gate: it flags body prose like "pass this value back to
/// Alef-generated bridge APIs" in partial templates that were never headers at all. Requiring the
/// contiguous "generated by" phrasing keeps this gate on lines that are actually trying to be
/// markers. ~keep
#[test]
fn no_shipped_template_stamps_a_marker_alef_would_refuse_to_read_back() {
    use crate::core::hash::content_has_alef_marker;

    /// A line that means to be a provenance marker: it claims generation and names alef.
    /// A line satisfying this that `content_has_alef_marker` still refuses is a broken marker.
    fn intends_to_mark(line: &str) -> bool {
        let lowered = line.to_ascii_lowercase();
        lowered.contains("generated by") && lowered.contains("alef")
    }

    fn collect_jinja(dir: &std::path::Path, found: &mut Vec<std::path::PathBuf>) {
        let entries = std::fs::read_dir(dir).unwrap_or_else(|err| panic!("read {}: {err}", dir.display()));
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                collect_jinja(&path, found);
            } else if path.extension().is_some_and(|ext| ext == "jinja") {
                found.push(path);
            }
        }
    }

    let src = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
    let mut templates = Vec::new();
    collect_jinja(&src, &mut templates);

    // Non-vacuity guard: a walk that finds nothing passes every assertion below and is
    // indistinguishable from a clean result. alef ships hundreds of templates; if this floor is
    // ever hit, the walk is broken, not the templates. ~keep
    assert!(
        templates.len() > 100,
        "expected the template walk to find hundreds of .jinja files under {}, found {} -- the \
         walk is broken and this test is checking nothing",
        src.display(),
        templates.len()
    );

    let mut refused: Vec<String> = Vec::new();
    let mut marked = 0usize;
    for path in &templates {
        let Ok(content) = std::fs::read_to_string(path) else {
            continue;
        };
        if content_has_alef_marker(&content) {
            marked += 1;
        } else if let Some(broken) = content.lines().find(|line| intends_to_mark(line)) {
            let relative = path.strip_prefix(&src).unwrap_or(path);
            refused.push(format!("  {}: {}", relative.display(), broken.trim()));
        }
    }

    // Second non-vacuity guard: the walk must actually reach self-marking templates, or every
    // near-miss branch above is dead and the test proves nothing about spellings. ~keep
    assert!(
        marked > 0,
        "no walked template carried a recognized alef marker, so the broken-marker check never ran"
    );

    assert!(
        refused.is_empty(),
        "these templates stamp a marker `content_has_alef_marker` refuses, so every file they \
         generate is un-ownable and silently re-refused forever:\n{}",
        refused.join("\n")
    );
}

/// The two marker forms a consumer census found that contain neither `generated by alef` nor any
/// case variant of it. Pinned verbatim as reported, because both live in shipped output — a
/// Homebrew `Brewfile` driving a published install path, and real C source in an R binding — and
/// because the substring predicate they defeat is the one thing standing between them and being
/// refused on every run forever.
///
/// A census that greps for the marker it expects cannot report the marker it does not: the
/// consumer's own first pass used a regex requiring `generated by alef`, so it was structurally
/// incapable of finding these two and reported a clean result over a conditioned population. They
/// surfaced only on a second pass keyed on `alef` and `do not edit` independently. ~keep
#[test]
fn the_two_non_conforming_marker_forms_a_consumer_census_found_are_recognized() {
    use crate::core::hash::content_has_alef_marker;

    let brewfile = "# Brewfile — managed by alef. DO NOT EDIT.\nbrew \"cmake\"\n";
    let r_entrypoint = "// Generated entrypoint: forwards to the extendr-generated init function.\n\
                        // Do not edit — regenerate with `alef generate`.\n#include <R.h>\n";

    assert!(
        content_has_alef_marker(brewfile),
        "a Brewfile saying `managed by alef` is an ownership claim; refusing it makes the file \
         unadoptable forever, and it drives a published install path"
    );
    assert!(
        content_has_alef_marker(r_entrypoint),
        "this header names alef and says do not edit, but never adjacently — a human reads it as a \
         marker and a contiguous substring test does not"
    );

    // Negative control. Without it, a predicate that accepted everything would satisfy the two
    // assertions above and look like a fix. ~keep
    assert!(
        !content_has_alef_marker("// Hand-written helper. Edit freely.\nint main(void) { return 0; }\n"),
        "a file making no ownership claim must still be refused"
    );
    assert!(
        !content_has_alef_marker("// Managed by hand; alef is not involved in this file.\n"),
        "naming alef in prose is not an ownership claim — the marker must be a contiguous phrase, \
         or any file discussing alef becomes alef-owned"
    );
}
