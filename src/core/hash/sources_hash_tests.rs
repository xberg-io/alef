#[test]
fn sources_hash_changes_with_content() {
    let dir = tempdir().unwrap();
    let s = write_file(dir.path(), "a.rs", "fn a() {}");
    let h_before = compute_sources_hash(std::slice::from_ref(&s)).unwrap();
    std::fs::write(&s, "fn a() { let _ = 1; }").unwrap();
    let h_after = compute_sources_hash(&[s]).unwrap();
    assert_ne!(h_before, h_after);
}

#[test]
fn file_hash_idempotent_under_strip_hash_line() {
    let bare = "// auto-generated by alef\nfn body() {}\n";
    let with_line = "// auto-generated by alef\n// alef:hash:deadbeef\nfn body() {}\n";

    let h1 = compute_file_hash(bare);
    let h2 = compute_file_hash(with_line);
    assert_eq!(h1, h2, "hash must ignore an existing alef:hash: line");
}

/// Anti-churn guarantee: no inputs-hash argument means an unrelated source/`alef.toml`
/// change cannot move an untouched file's stamp. See `core::hash`'s module doc. ~keep
#[test]
fn file_hash_does_not_change_when_generation_inputs_change() {
    let content = "// auto-generated by alef\nfn body() {}\n";
    let h_a = compute_file_hash(content);
    let h_b = compute_file_hash(content);
    assert_eq!(
        h_a, h_b,
        "identical file content must hash identically regardless of generation inputs -- \
         `compute_file_hash` has no inputs_hash parameter to differ on"
    );
}

#[test]
fn file_hash_changes_when_content_changes() {
    let h_a = compute_file_hash("fn a() {}\n");
    let h_b = compute_file_hash("fn b() {}\n");
    assert_ne!(h_a, h_b);
}

/// ~keep This asserted only that the digest was 64 hex chars, so it passed no matter what
/// `compute_file_hash` folded in -- it could never have failed and gave false confidence that
/// the pin was already excluded, which it was not. The real independence claim is now proved by
/// `inputs_hash_alef_version_pin_table`; what is left here is the domain-separator check the
/// length assertion was actually standing in for.
#[test]
fn file_hash_is_domain_separated_from_a_bare_blake3_digest() {
    let content = "fn a() {}\n";
    let h = compute_file_hash(content);
    assert_eq!(h.len(), 64, "blake3 hex output is 64 chars");
    assert_ne!(
        h,
        blake3::hash(content.as_bytes()).to_hex().to_string(),
        "file hash must use its own domain separator, not digest the content alone"
    );
}

