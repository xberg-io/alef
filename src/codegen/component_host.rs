//! Standalone Rust host module for hosts that load components without an ffi/pyo3 binding.
//!
//! A pure-Rust host (one that links the core crate directly and loads downloadable components
//! itself) otherwise has to hand-write the `#[repr(C)]` tables, copy `CONTRACT_HASH` out of the
//! lock and spell the entry-symbol names. This module emits all of that into one file, reusing
//! the proxy generator the binding backends use.

use crate::codegen::component::{ResolvedComponent, entry_point_symbol_literal, resolve_components};
use crate::codegen::component_proxy::generate_component_proxies;
use crate::codegen::naming::to_constant_name;
use crate::core::backend::GeneratedFile;
use crate::core::config::ResolvedCrateConfig;
use crate::core::ir::ApiSurface;
use anyhow::Result;
use std::fmt::Write as _;
use std::path::PathBuf;

/// Marker line `generate_component_proxies` puts above each proxy; the module-level header
/// stamped by the writer replaces it.
const PROXY_HEADER_LINE: &str = "// This file is auto-generated by alef. DO NOT EDIT.\n";

/// Generate the host module for `config`, or `None` when `[crates.component_host]` is unset.
///
/// # Errors
///
/// Fails when a configured component cannot be resolved against `api`.
pub fn generate_component_host(api: &ApiSurface, config: &ResolvedCrateConfig) -> Result<Option<GeneratedFile>> {
    let Some(host) = &config.component_host else {
        return Ok(None);
    };
    let resolved = resolve_components(api, config)?;
    let content = render_host_module(config, &resolved, host.effective_lock_path())?;
    Ok(Some(GeneratedFile {
        path: PathBuf::from(&host.output),
        content,
        generated_header: true,
    }))
}

/// Render the module body for already-resolved components. `lock_path` is the
/// `include_str!` argument, relative to the generated file.
pub(crate) fn render_host_module(
    config: &ResolvedCrateConfig,
    resolved: &[ResolvedComponent],
    lock_path: &str,
) -> Result<String> {
    let proxies = generate_component_proxies(config, resolved)?.replace(PROXY_HEADER_LINE, "");
    let mut out = String::new();
    out.push_str("//! Standalone host for this crate's downloadable components.\n\n");
    out.push_str("#![allow(dead_code)]\n\n");
    out.push_str("use alef_component_runtime::{ComponentError, ComponentManager};\n");
    out.push_str("use std::path::PathBuf;\n\n");

    let ids = resolved
        .iter()
        .map(|component| format!("{:?}", component.component_name))
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(out, "/// Every configured component id.")?;
    writeln!(out, "pub const COMPONENT_IDS: &[&str] = &[{ids}];\n")?;

    let mut emitted = std::collections::BTreeSet::new();
    for provided in resolved.iter().flat_map(|component| &component.provides) {
        let contract = &provided.contract.name;
        if !emitted.insert(contract.clone()) {
            continue;
        }
        let constant = to_constant_name(contract);
        writeln!(
            out,
            "/// Contract hash of `{contract}`, as recorded in the component lock."
        )?;
        writeln!(
            out,
            "pub const {constant}_CONTRACT_HASH_HEX: &str = {:?};",
            provided.contract.hash_hex()?
        )?;
        writeln!(out, "/// Entry symbol of the `{contract}` producer, NUL-terminated.")?;
        writeln!(
            out,
            "pub const {constant}_ENTRY_SYMBOL: &[u8] = {};\n",
            entry_point_symbol_literal(contract)
        )?;
    }

    out.push_str(
        "/// The host's target triple, when components are published for it.\npub fn host_target() -> Option<&'static str> {\n    alef_component_runtime::target::host_target()\n}\n\n",
    );
    out.push_str(&proxies);
    write!(out, "{}", manager_constructor(lock_path))?;
    Ok(out)
}

fn manager_constructor(lock_path: &str) -> String {
    format!(
        r#"/// Build a manager over the embedded `components.lock.json`.
///
/// `cache_root` is where verified artifacts are stored; `offline` makes a missing artifact an
/// error instead of a download. On a host with no published target the manager is built for
/// `unsupported-host`, so every component lookup fails with `ArtifactNotFound` naming it.
pub fn component_manager(cache_root: PathBuf, offline: bool) -> Result<ComponentManager, ComponentError> {{
    let lock = serde_json::from_str(include_str!({lock_path:?}))?;
    let target = host_target().unwrap_or("unsupported-host");
    ComponentManager::from_lock(lock, cache_root, target, alef_component_abi::AlefHostApiV1::EMPTY)
        .map(|manager| manager.offline(offline))
}}
"#
    )
}

/// One `(component, contract, hex hash)` row per provided contract, in the order given; the hash
/// is exactly the one recorded in the component lock.
pub fn contract_hash_rows(resolved: &[ResolvedComponent]) -> Result<Vec<(String, String, String)>> {
    let mut rows = Vec::new();
    for component in resolved {
        for provided in &component.provides {
            rows.push((
                component.component_name.clone(),
                provided.contract.name.clone(),
                provided.contract.hash_hex()?,
            ));
        }
    }
    Ok(rows)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::core::config::{ComponentConfig, ComponentContractConfig, ComponentHostConfig, ComponentProvidesConfig};
    use crate::core::ir::{MethodDef, ParamDef, ReceiverKind, TypeDef, TypeRef};

    fn fixture() -> (ApiSurface, ResolvedCrateConfig) {
        let api = ApiSurface {
            crate_name: "demo_core".into(),
            version: "1.0.0".into(),
            types: vec![TypeDef {
                name: "Codec".into(),
                rust_path: "demo_core::Codec".into(),
                is_trait: true,
                is_opaque: true,
                methods: vec![MethodDef {
                    name: "transform".into(),
                    params: vec![ParamDef {
                        name: "input".into(),
                        ty: TypeRef::Bytes,
                        is_ref: true,
                        ..ParamDef::default()
                    }],
                    return_type: TypeRef::Bytes,
                    receiver: Some(ReceiverKind::Ref),
                    error_type: Some("Error".into()),
                    ..MethodDef::default()
                }],
                ..TypeDef::default()
            }],
            ..ApiSurface::default()
        };
        let config = ResolvedCrateConfig {
            name: "demo-core".into(),
            component_contracts: vec![ComponentContractConfig {
                name: "codec".into(),
                trait_path: "demo_core::Codec".into(),
                interface_version: 1,
            }],
            components: vec![ComponentConfig {
                name: "reverse".into(),
                provides: vec![ComponentProvidesConfig {
                    contract: "codec".into(),
                    implementation: "demo_core::ReverseCodec".into(),
                }],
                features: vec!["reverse".into()],
                default_features: false,
                targets: Some(vec!["x86_64-unknown-linux-gnu".into()]),
                bundled_on: Vec::new(),
                extra_dependencies: Default::default(),
            }],
            component_host: Some(ComponentHostConfig {
                output: "crates/host/src/components_gen.rs".into(),
                lock_path: Some("../components.lock.json".into()),
            }),
            ..ResolvedCrateConfig::default()
        };
        (api, config)
    }

    #[test]
    fn host_module_holds_proxy_hash_entry_symbol_and_constructor() {
        let (api, config) = fixture();
        let file = generate_component_host(&api, &config)
            .unwrap()
            .expect("host configured");
        assert_eq!(file.path, PathBuf::from("crates/host/src/components_gen.rs"));
        assert!(file.generated_header);
        let generated = &file.content;
        assert!(generated.contains("pub struct CodecProxy"), "{generated}");
        assert!(generated.contains("const CONTRACT_HASH: [u8; 32]"), "{generated}");
        assert!(
            generated.contains("pub const CODEC_ENTRY_SYMBOL: &[u8] = b\"alef_component_entry_v1_codec\\0\";"),
            "{generated}"
        );
        assert!(
            generated.contains("pub const CODEC_CONTRACT_HASH_HEX: &str = \""),
            "{generated}"
        );
        assert!(
            generated.contains("pub const COMPONENT_IDS: &[&str] = &[\"reverse\"];"),
            "{generated}"
        );
        assert!(
            generated.contains("alef_component_runtime::target::host_target()"),
            "{generated}"
        );
        assert!(
            generated.contains(
                "pub fn component_manager(cache_root: PathBuf, offline: bool) -> Result<ComponentManager, ComponentError>"
            ),
            "{generated}"
        );
        assert!(
            generated.contains("include_str!(\"../components.lock.json\")"),
            "{generated}"
        );
        assert!(!generated.contains("DO NOT EDIT"), "{generated}");
        syn::parse_file(generated).expect("generated host module must be valid Rust syntax");
    }

    #[test]
    fn hash_constant_matches_the_contract_hash_rows() {
        let (api, config) = fixture();
        let rows = contract_hash_rows(&resolve_components(&api, &config).unwrap()).unwrap();
        assert_eq!(rows.len(), 1);
        assert_eq!(rows[0].0, "reverse");
        assert_eq!(rows[0].1, "codec");
        assert_eq!(rows[0].2.len(), 64);
        let file = generate_component_host(&api, &config).unwrap().unwrap();
        assert!(file.content.contains(&rows[0].2), "{}", file.content);
    }

    #[test]
    fn no_host_module_without_configuration() {
        let (api, mut config) = fixture();
        config.component_host = None;
        assert!(generate_component_host(&api, &config).unwrap().is_none());
    }
}
