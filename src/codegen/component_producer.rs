    #[test]
    fn emits_profile_crate_header_and_async_task() {
        let (api, config) = fixture();
        let files = generate_component_producers(&api, &config).unwrap();
        assert_eq!(files.len(), 3);
        let source = files.iter().find(|file| file.path.ends_with("src/lib.rs")).unwrap();
        assert!(source.content.contains("alef_component_entry_v1_extractor"));
        assert!(source.content.contains("extractor_component_extract"));
        assert!(source.content.contains("std::thread::spawn"));
        syn::parse_file(&source.content).expect("generated component producer must be valid Rust syntax");
        assert!(
            source
                .content
                .contains("assert_send_sync::<ExtractorComponentImplementation>();"),
            "{}",
            source.content
        );
        assert!(source.content.contains("fn panic_message(payload: &(dyn Any + Send))"));
        assert!(
            source
                .content
                .contains("error_buffer(format!(\"component method panicked: {}\", panic_message(&*payload)))"),
            "{}",
            source.content
        );
        assert!(source.content.contains("alef_component_abi::HostApi::from_raw(host)"));
        assert!(source.content.contains("create_component(host: *const AlefHostApiV1"));
        assert!(
            source
                .content
                .contains("Construct::<ExtractorComponentImplementation>::new()")
        );
        let manifest = files.iter().find(|file| file.path.ends_with("Cargo.toml")).unwrap();
        assert!(manifest.content.contains("features = [\"pdf\"]"));
        assert!(manifest.content.contains("crate-type = [\"cdylib\"]"));
        assert!(
            manifest
                .content
                .contains(&format!("alef-component-abi = \"={}\"", env!("CARGO_PKG_VERSION"))),
            "{}",
            manifest.content
        );
    }

    #[test]
    fn extra_dependencies_are_emitted_into_the_producer_manifest() {
        let (api, mut config) = fixture();
        config.components[0].extra_dependencies.insert(
            "pdf-engine".into(),
            serde_json::json!({ "version": "2", "features": ["fast"] }),
        );
        config.components[0]
            .extra_dependencies
            .insert("serde_json".into(), serde_json::json!("1"));
        let files = generate_component_producers(&api, &config).unwrap();
        let manifest = files.iter().find(|file| file.path.ends_with("Cargo.toml")).unwrap();
        assert!(
            manifest.content.contains("serde_json = \"1\"\n"),
            "{}",
            manifest.content
        );
        let line = manifest
            .content
            .lines()
            .find(|line| line.starts_with("pdf-engine = "))
            .unwrap();
        assert!(
            line.contains("\"version\" = \"2\"") && line.contains("\"features\" = [\"fast\"]"),
            "{line}"
        );
        let parsed: toml::Table = toml::from_str(&manifest.content).expect("manifest must stay valid TOML");
        assert!(parsed["dependencies"].as_table().unwrap().contains_key("pdf-engine"));
    }

