/// Generate one isolated producer crate per configured component, exporting one
/// entrypoint and function table per contract it provides.
pub fn generate_component_producers(api: &ApiSurface, config: &ResolvedCrateConfig) -> Result<Vec<GeneratedFile>> {
    let components = crate::codegen::component::resolve_components(api, config)?;
    let mut files = Vec::with_capacity(components.len() * 3);
    for component in components {
        if component.producer_language == crate::core::config::ComponentProducerLanguage::Executable {
            continue;
        }
        if component.producer_language == crate::core::config::ComponentProducerLanguage::Go {
            files.extend(super::component_go::generate(api, config, &component)?);
            continue;
        }
        for provided in &component.provides {
            validate_producer_types(&provided.contract)?;
        }
        let crate_dir = deps::component_crate_dir(config, &component);
        files.push(GeneratedFile {
            path: crate_dir.join("Cargo.toml"),
            content: producer_manifest(api, config, &component)?,
            generated_header: true,
        });
        files.push(GeneratedFile {
            path: crate_dir.join("src/lib.rs"),
            content: producer_source(api, &component)?,
            generated_header: true,
        });
        for provided in &component.provides {
            files.push(GeneratedFile {
                path: crate_dir.join(format!("include/{}.h", provided.contract.name.to_snake_case())),
                content: provided.contract.c_header(),
                generated_header: true,
            });
        }
    }
    Ok(files)
}

fn component_has_async(component: &ResolvedComponent) -> bool {
    component
        .provides
        .iter()
        .any(|provided| provided.contract.methods.iter().any(|method| method.is_async))
}

fn producer_manifest(api: &ApiSurface, config: &ResolvedCrateConfig, component: &ResolvedComponent) -> Result<String> {
    let package = format!(
        "{}-{}-component",
        config.core_crate_dir(),
        component.component_name.replace('_', "-")
    );
    let dependencies = deps::producer_dependencies(config, component, &api.version, &std::env::current_dir()?)?;
    let mut extra = String::new();
    if component_has_async(component) {
        extra.push_str("futures = \"0.3\"\n");
    }
    for (name, spec) in &component.extra_dependencies {
        let rendered = crate::core::config::component::render_dependency_spec(spec).map_err(|reason| {
            anyhow::anyhow!(
                "component `{}` extra dependency `{name}`: {reason}",
                component.component_name
            )
        })?;
        writeln!(extra, "{name} = {rendered}")?;
    }
    let license = license::producer_license(config)?
        .map(|license| format!("license = {}\n", toml::Value::String(license)))
        .unwrap_or_default();
    Ok(format!(
        r#"[package]
name = "{package}"
version = "{version}"
edition = "2024"
publish = false
{license}
[lib]
crate-type = ["cdylib"]

[dependencies]
alef-component-abi = "={alef_version}"
{dependencies}{extra}"#,
        version = api.version,
        alef_version = env!("CARGO_PKG_VERSION"),
    ))
}

/// Emit the producer crate's `src/lib.rs`: the imports its body uses, then one self-contained
/// block per provided contract (its own implementation type alias, function table, descriptor,
/// and entry point). Buffer, panic and task helpers come from `alef_component_abi`.
fn producer_source(api: &ApiSurface, component: &ResolvedComponent) -> Result<String> {
    let mut body = String::new();
    writeln!(body, "const COMPONENT_ID: &[u8] = b\"{}\";", component.component_name)?;
    writeln!(body, "const COMPONENT_VERSION: &[u8] = b\"{}\";", api.version)?;
    body.push('\n');
    let feature_hash = byte_array(&feature_set_hash(&component.features, component.default_features));
    for provided in &component.provides {
        contract::emit_contract_block(&mut body, provided, &feature_hash)?;
    }

    let mut out = String::new();
    writeln!(out, "// This file is auto-generated by alef. DO NOT EDIT.")?;
    out.push_str("//! Native component producer exporting versioned contract entrypoints.\n\n");
    out.push_str(&used_imports(&body));
    out.push('\n');
    out.push_str(body.trim_end());
    out.push('\n');
    Ok(out)
}

/// The names a generated producer body may refer to unqualified, grouped by the module that
/// exports them.
const IMPORTABLE: &[(&str, &[&str])] = &[
    (
        "alef_component_abi",
        &[
            "AlefComponentV1",
            "AlefHostApiV1",
            "AlefOwnedBuffer",
            "AlefSlice",
            "AlefStatus",
            "AlefStr",
            "AlefTaskV1",
            "SyncStatic",
            "cancel_flag_task",
            "error_buffer",
            "owned_buffer",
            "panic_message",
        ],
    ),
    ("std::ffi", &["c_char", "c_void"]),
    ("std::panic", &["AssertUnwindSafe", "catch_unwind"]),
    ("std::sync", &["Arc"]),
    ("std::sync::atomic", &["AtomicBool", "Ordering"]),
];

/// `use` lines for exactly the [`IMPORTABLE`] names `body` mentions, so a producer never carries
/// an unused import whichever wire types and method kinds its contracts use.
fn used_imports(body: &str) -> String {
    let mut out = String::new();
    for (module, names) in IMPORTABLE {
        let used = names
            .iter()
            .copied()
            .filter(|name| mentions_identifier(body, name))
            .collect::<Vec<_>>();
        match used.as_slice() {
            [] => {}
            [name] => out.push_str(&format!("use {module}::{name};\n")),
            names => out.push_str(&format!("use {module}::{{{}}};\n", names.join(", "))),
        }
    }
    out
}

/// Whether `ident` occurs in `body` as a whole identifier, not as part of a longer one or as a
/// path segment after `::` (a qualified `std::sync::atomic::Ordering` needs no import).
fn mentions_identifier(body: &str, ident: &str) -> bool {
    let is_ident_char = |c: char| c.is_ascii_alphanumeric() || c == '_';
    body.match_indices(ident).any(|(start, _)| {
        let before = &body[..start];
        let after = &body[start + ident.len()..];
        !before.ends_with(is_ident_char) && !before.ends_with("::") && !after.starts_with(is_ident_char)
    })
}

fn validate_producer_types(contract: &ComponentContractIr) -> Result<()> {
    fn supported(ty: &WireType) -> bool {
        matches!(
            ty,
            WireType::Unit
                | WireType::Bool
                | WireType::U8
                | WireType::U16
                | WireType::U32
                | WireType::U64
                | WireType::I8
                | WireType::I16
                | WireType::I32
                | WireType::I64
                | WireType::F32
                | WireType::F64
                | WireType::Utf8
                | WireType::Bytes
        )
    }
    for method in &contract.methods {
        for param in &method.params {
            if !supported(&param.ty) {
                bail!(
                    "component producer does not yet support {:?} in parameter {}::{}",
                    param.ty,
                    method.name,
                    param.name
                );
            }
        }
        if !supported(&method.result) {
            bail!(
                "component producer does not yet support {:?} as result of {}",
                method.result,
                method.name
            );
        }
    }
    Ok(())
}

pub(super) fn feature_set_hash(features: &[String], default_features: bool) -> [u8; 32] {
    let mut normalized = features.to_vec();
    normalized.sort();
    normalized.dedup();
    let input = serde_json::json!({
        "default_features": default_features,
        "features": normalized,
    });
    let mut hasher = Sha256::new();
    hasher.update(serde_json::to_vec(&input).expect("feature hash input is serializable"));
    hasher.finalize().into()
}

fn byte_array(bytes: &[u8; 32]) -> String {
    format!("[{}]", bytes.iter().map(u8::to_string).collect::<Vec<_>>().join(", "))
}

