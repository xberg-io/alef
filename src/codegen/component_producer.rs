    #[test]
    fn every_generated_producer_unsafe_block_carries_a_safety_comment() {
        let (api, config) = fixture();
        let source = producer_lib(&api, &config);
        let lines: Vec<&str> = source.lines().collect();
        let mut blocks = 0;
        for (index, line) in lines.iter().enumerate() {
            if !line.contains("unsafe {") {
                continue;
            }
            blocks += 1;
            let documented = lines[..index]
                .iter()
                .rev()
                .take_while(|previous| previous.trim_start().starts_with("//"))
                .any(|comment| comment.contains("SAFETY:"));
            assert!(
                documented,
                "undocumented unsafe block at line {index}: {line}\n{source}"
            );
        }
        assert!(
            blocks >= 10,
            "expected the lifecycle, method and descriptor blocks, found {blocks}"
        );
    }

