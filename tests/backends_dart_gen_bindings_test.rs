fn find_dart_src(files: &[alef::core::backend::GeneratedFile]) -> Option<&str> {
    files
        .iter()
        .find(|f| {
            let p = f.path.to_string_lossy();
            p.ends_with(".dart") && p.contains("/lib/src/") && !p.ends_with("traits.dart")
        })
        .map(|f| f.content.as_str())
}

fn find_traits_src(files: &[alef::core::backend::GeneratedFile]) -> Option<&str> {
    files
        .iter()
        .find(|f| f.path.to_string_lossy().ends_with("traits.dart"))
        .map(|f| f.content.as_str())
}

