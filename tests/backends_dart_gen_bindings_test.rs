/// `export 'traits.dart';` alone does not bring the trait names into the file's own scope, so
/// `comment_references` flags every doc comment (`[OcrBackend]`, etc.) that points at a type
/// declared in traits.dart. The module file must also `import 'traits.dart';` — but ONLY when it
/// actually names a trait, since emitting it unconditionally trips `unused_import` otherwise.
#[test]
fn module_file_omits_traits_import_when_no_trait_is_referenced() {
    let api = ApiSurface {
        crate_name: "demo-crate".into(),
        version: "0.1.0".into(),
        types: vec![],
        functions: vec![],
        enums: vec![],
        errors: vec![],
        excluded_type_paths: ::std::collections::BTreeMap::new(),
        excluded_trait_names: ::std::collections::HashSet::new(),
        services: vec![],
        handler_contracts: vec![],
        unsupported_public_items: Vec::new(),
    };

    let files = DartBackend.generate_bindings(&api, &make_config()).unwrap();
    let content = files
        .iter()
        .find(|f| {
            f.path
                .to_string_lossy()
                .replace('\\', "/")
                .ends_with("/src/demo_crate.dart")
        })
        .map(|f| f.content.as_str())
        .expect("missing src/demo_crate.dart");

    assert!(
        content.contains("export 'traits.dart';"),
        "the module file must still re-export traits.dart: {content}"
    );
    assert!(
        !content.contains("import 'traits.dart';"),
        "a module file that names no trait must not import traits.dart — dart analyze \
         reports it as unused_import: {content}"
    );
}

