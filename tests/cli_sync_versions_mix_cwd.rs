#![cfg(unix)]

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::Path;
use std::process::{Command, Output};

fn fixture(root: &Path) {
    fs::create_dir_all(root.join("src")).unwrap();
    fs::create_dir_all(root.join("bin")).unwrap();
    fs::write(root.join("src/lib.rs"), "pub fn value() -> u32 { 1 }\n").unwrap();
    fs::write(
        root.join("Cargo.toml"),
        "[package]\nname='probe'\nversion='1.0.1'\nedition='2024'\n",
    )
    .unwrap();
    fs::write(root.join("alef.toml"), "[workspace]\nlanguages=['elixir']\n[workspace.sync]\nextra_paths=['other projects/*/mix.exs','mix.exs']\n[[crates]]\nname='probe'\ncore_import='probe'\nsources=['src/lib.rs']\n[crates.elixir]\napp_name='probe'\n").unwrap();
    let mix = root.join("bin/mix");
    fs::write(
        &mix,
        "#!/bin/sh\nprintf '%s\\t%s\\n' \"$PWD\" \"$*\" >> \"$ALEF_MIX_TRACE\"\nexit 42\n",
    )
    .unwrap();
    fs::set_permissions(mix, fs::Permissions::from_mode(0o755)).unwrap();
}

fn write_mix(root: &Path, directory: &str, version: &str) {
    let directory = root.join(directory);
    fs::create_dir_all(&directory).unwrap();
    fs::write(directory.join("mix.exs"), format!("# Generated by alef\ndefmodule Probe.MixProject do\n  use Mix.Project\n  def project, do: [app: :probe, version: \"{version}\"]\nend\n")).unwrap();
}

fn run(root: &Path) -> Output {
    let path = std::env::join_paths(
        std::iter::once(root.join("bin")).chain(std::env::split_paths(&std::env::var_os("PATH").unwrap())),
    )
    .unwrap();
    Command::new(env!("CARGO_BIN_EXE_alef"))
        .args(["sync-versions", "--skip-swift-checksum"])
        .current_dir(root)
        .env("PATH", path)
        .env("ALEF_MIX_TRACE", root.join("mix-calls.txt"))
        .env("CARGO_NET_OFFLINE", "true")
        .output()
        .unwrap()
}

fn assert_success(output: &Output) {
    assert!(
        output.status.success(),
        "stdout={} stderr={}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

#[test]
fn changed_nested_mix_refresh_uses_project_directory_and_remains_best_effort() {
    let directory = tempfile::tempdir().unwrap();
    let root = directory.path().canonicalize().unwrap();
    fixture(&root);
    write_mix(&root, "packages/elixir", "1.0.0");
    assert_success(&run(&root));
    let trace = fs::read_to_string(root.join("mix-calls.txt")).unwrap();
    assert_eq!(trace, format!("{}\tdeps.get\n", root.join("packages/elixir").display()));
    let manifest = fs::read_to_string(root.join("packages/elixir/mix.exs")).unwrap();
    assert!(manifest.contains("version: \"1.0.1\""));
}

#[test]
fn changed_mix_projects_each_refresh_once_including_paths_with_spaces() {
    let directory = tempfile::tempdir().unwrap();
    let root = directory.path().canonicalize().unwrap();
    fixture(&root);
    for path in ["packages/elixir", "other projects/elixir two", "."] {
        write_mix(&root, path, "1.0.0");
    }
    write_mix(&root, "other projects/already current", "1.0.1");
    assert_success(&run(&root));
    let trace = fs::read_to_string(root.join("mix-calls.txt")).unwrap();
    let mut calls: Vec<_> = trace.lines().map(str::to_owned).collect();
    calls.sort();
    let mut expected: Vec<_> = [
        root.clone(),
        root.join("packages/elixir"),
        root.join("other projects/elixir two"),
    ]
    .into_iter()
    .map(|path| format!("{}\tdeps.get", path.display()))
    .collect();
    expected.sort();
    assert_eq!(calls.len(), 3);
    assert_eq!(calls, expected);
}

#[test]
fn unchanged_mix_project_does_not_refresh_dependencies() {
    let directory = tempfile::tempdir().unwrap();
    let root = directory.path().canonicalize().unwrap();
    fixture(&root);
    write_mix(&root, "packages/elixir", "1.0.1");
    assert_success(&run(&root));
    assert!(!root.join("mix-calls.txt").exists());
}
