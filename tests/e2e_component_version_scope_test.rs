use std::fs;
use std::path::Path;
use std::process::Command;

fn write(root: &Path, path: &str, content: &str) {
    let path = root.join(path);
    fs::create_dir_all(path.parent().expect("parent")).expect("create fixture directory");
    fs::write(path, content).expect("write fixture");
}

fn package(root: &Path, directory: &str, name: &str, version: &str, dependencies: &str) {
    write(
        root,
        &format!("{directory}/Cargo.toml"),
        &format!("[package]\nname = \"{name}\"\nversion = \"{version}\"\nedition = \"2024\"\n{dependencies}"),
    );
    write(
        root,
        &format!("{directory}/src/lib.rs"),
        "pub fn value() -> u32 { 1 }\n",
    );
}

fn fixture(root: &Path) {
    write(
        root,
        "Cargo.toml",
        concat!(
            "[workspace]\nresolver = \"2\"\nmembers = [\"crates/*\"]\n",
            "[workspace.dependencies]\n",
            "helper_alias = { package = \"helper-lib\", path = \"crates/helper\", version = \"9.4.0\" }\n",
            "core_alias = { package = \"scope-core\", path = \"crates/core\", version = \"1.0.0\" }\n"
        ),
    );
    package(root, "crates/core", "scope-core", "2.0.0", "[features]\nnative = []\n");
    write(
        root,
        "crates/core/src/lib.rs",
        "pub trait Codec { fn encode(&self, input: Vec<u8>) -> Vec<u8>; }\npub struct NativeCodec;\n",
    );
    package(root, "crates/helper", "helper-lib", "9.4.0", "");
    package(
        root,
        "crates/helper-sdk",
        "helper-sdk",
        "9.4.0",
        "[dependencies]\nhelper_alias = { workspace = true }\n",
    );
    for (directory, name, dependency) in [
        ("crates/core-sdk", "core-sdk", "core_alias = { workspace = true }"),
        (
            "crates/core-sdk-child",
            "core-sdk-child",
            "sdk = { package = \"core-sdk\", path = \"../core-sdk\", version = \"1.0.0\" }",
        ),
    ] {
        package(
            root,
            directory,
            name,
            "1.0.0",
            &format!("[dependencies]\n{dependency}\n"),
        );
        let path = root.join(directory).join("Cargo.toml");
        let manifest = fs::read_to_string(&path).expect("core SDK manifest");
        fs::write(
            path,
            format!("# This file is auto-generated by alef. DO NOT EDIT.\n{manifest}"),
        )
        .expect("mark core SDK");
    }
    let sdk_path = root.join("crates/helper-sdk/Cargo.toml");
    let sdk = fs::read_to_string(&sdk_path).expect("helper SDK");
    fs::write(
        sdk_path,
        format!("# This file is auto-generated by alef. DO NOT EDIT.\n{sdk}"),
    )
    .expect("mark helper SDK");
    package(root, "../outside", "outside-lib", "7.2.0", "[workspace]\n");
    package(
        root,
        "crates/client",
        "client",
        "6.0.0",
        concat!(
            "[dependencies]\n",
            "helper_alias = { workspace = true }\n",
            "core_alias = { workspace = true }\n",
            "outside = { package = \"outside-lib\", path = \"../../../outside\", version = \"7.2.0\" }\n"
        ),
    );
    write(
        root,
        "alef.toml",
        concat!(
            "[workspace]\nlanguages = []\n",
            "[[crates]]\nname = \"scope-core\"\nsources = [\"crates/core/src/lib.rs\"]\n",
            "version_from = \"crates/core/Cargo.toml\"\n",
            "[[crates.component_contracts]]\nname = \"codec\"\ntrait_path = \"scope_core::Codec\"\n",
            "interface_version = 1\n",
            "[[crates.components]]\nname = \"native\"\nfeatures = [\"native\"]\ndefault_features = false\n",
            "[[crates.components.provides]]\ncontract = \"codec\"\nimplementation = \"scope_core::NativeCodec\"\n"
        ),
    );
}

#[test]
fn generate_component_preserves_unrelated_workspace_versions_and_reconciles_core_pin() {
    let temporary = tempfile::tempdir().expect("temporary directory");
    let root = temporary.path().join("workspace");
    fixture(&root);
    let protected = [
        "crates/helper/Cargo.toml",
        "crates/helper-sdk/Cargo.toml",
        "crates/client/Cargo.toml",
        "../outside/Cargo.toml",
    ];
    let before: Vec<_> = protected
        .iter()
        .map(|path| fs::read(root.join(path)).expect("before"))
        .collect();
    let members = alef::publish::workspace::workspace_member_crates(&root).expect("resolve fixture members");
    assert!(members.names.contains("scope-core"), "selected core must resolve");
    assert!(members.names.contains("helper-lib"), "unrelated helper must resolve");
    let output = Command::new(env!("CARGO_BIN_EXE_alef"))
        .current_dir(&root)
        .args(["generate", "--skip-compile"])
        .output()
        .expect("run generate");
    assert!(
        output.status.success(),
        "generate failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    for (path, bytes) in protected.iter().zip(before) {
        assert_eq!(
            fs::read(root.join(path)).expect("after"),
            bytes,
            "unrelated manifest changed: {path}"
        );
    }
    let root_manifest = fs::read_to_string(root.join("Cargo.toml")).expect("root manifest");
    assert!(
        root_manifest
            .contains("helper_alias = { package = \"helper-lib\", path = \"crates/helper\", version = \"9.4.0\" }")
    );
    let document: toml::Value = toml::from_str(&root_manifest).expect("valid root TOML");
    assert_eq!(
        document["workspace"]["dependencies"]["core_alias"]["version"].as_str(),
        Some("2.0.0")
    );
    for path in ["crates/core-sdk/Cargo.toml", "crates/core-sdk-child/Cargo.toml"] {
        let content = fs::read_to_string(root.join(path)).expect("selected generated SDK");
        let document: toml::Value = toml::from_str(&content).expect("SDK TOML");
        assert_eq!(document["package"]["version"].as_str(), Some("2.0.0"), "{path}");
    }
    let child = fs::read_to_string(root.join("crates/core-sdk-child/Cargo.toml")).expect("transitive SDK");
    let child: toml::Value = toml::from_str(&child).expect("child TOML");
    assert_eq!(child["dependencies"]["sdk"]["version"].as_str(), Some("2.0.0"));
    assert!(
        root.join("crates/core-native-component/src/lib.rs").is_file(),
        "component was not generated"
    );
}

fn fork_sdk_fixture(root: &Path) {
    package(root, "../fork-core", "scope-core", "7.2.0", "[workspace]\n");
    let manifest = root.join("Cargo.toml");
    let content = fs::read_to_string(&manifest).expect("root manifest");
    fs::write(
        manifest,
        format!("{content}fork_alias = {{ package = \"scope-core\", path = \"../fork-core\", version = \"7.2.0\" }}\n"),
    )
    .expect("add inherited external source");
    for (directory, name, dependency) in [
        (
            "crates/fork-sdk",
            "fork-sdk",
            "foreign = { package = \"scope-core\", path = \"../../../fork-core\", version = \"7.2.0\" }\nfork_alias = { workspace = true }",
        ),
        (
            "crates/fork-sdk-child",
            "fork-sdk-child",
            "fork = { package = \"fork-sdk\", path = \"../fork-sdk\", version = \"7.2.0\" }",
        ),
    ] {
        package(
            root,
            directory,
            name,
            "7.2.0",
            &format!("[dependencies]\n{dependency}\n"),
        );
        let path = root.join(directory).join("Cargo.toml");
        let content = fs::read_to_string(&path).expect("fork SDK manifest");
        fs::write(
            path,
            format!("# This file is auto-generated by alef. DO NOT EDIT.\n{content}"),
        )
        .expect("mark fork SDK");
    }
    let client_path = root.join("crates/client/Cargo.toml");
    let client = fs::read_to_string(&client_path).expect("client");
    fs::write(
        client_path,
        format!(
            "{client}foreign_core = {{ package = \"scope-core\", path = \"../../../fork-core\", version = \"7.2.0\" }}\n"
        ),
    )
    .expect("add unowned client fork dependency");
}

#[test]
fn generate_preserves_external_same_name_core_dependencies_and_their_marked_sdk_family() {
    let temporary = tempfile::tempdir().expect("temporary directory");
    let root = temporary.path().join("workspace");
    fixture(&root);
    fork_sdk_fixture(&root);
    let selected = root
        .join("crates/core/Cargo.toml")
        .canonicalize()
        .expect("selected core");
    let fork = root
        .join("crates/fork-sdk/../../../fork-core/Cargo.toml")
        .canonicalize()
        .expect("fork core");
    assert_ne!(selected, fork, "same-name cores must resolve to distinct manifests");
    let fork_content = fs::read_to_string(&fork).expect("resolved fork");
    let fork_document: toml::Value = toml::from_str(&fork_content).expect("fork TOML");
    assert_eq!(fork_document["package"]["name"].as_str(), Some("scope-core"));
    let protected = [
        "crates/fork-sdk/Cargo.toml",
        "crates/fork-sdk-child/Cargo.toml",
        "crates/client/Cargo.toml",
    ];
    let before: Vec<_> = protected
        .iter()
        .map(|path| fs::read(root.join(path)).expect("before"))
        .collect();
    let output = Command::new(env!("CARGO_BIN_EXE_alef"))
        .current_dir(&root)
        .args(["generate", "--skip-compile"])
        .output()
        .expect("run generate");
    assert!(
        output.status.success(),
        "generate failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    for (path, bytes) in protected.iter().zip(before) {
        assert_eq!(
            fs::read(root.join(path)).expect("after"),
            bytes,
            "external core reference changed: {path}"
        );
    }
    let root_manifest = fs::read_to_string(root.join("Cargo.toml")).expect("root manifest");
    let root_document: toml::Value = toml::from_str(&root_manifest).expect("root TOML");
    assert_eq!(
        root_document["workspace"]["dependencies"]["core_alias"]["version"].as_str(),
        Some("2.0.0")
    );
    assert_eq!(
        root_document["workspace"]["dependencies"]["fork_alias"]["version"].as_str(),
        Some("7.2.0")
    );
}

#[test]
fn generate_reconciles_selected_core_discovered_as_implicit_workspace_member() {
    let temporary = tempfile::tempdir().expect("temporary directory");
    let root = temporary.path().join("workspace");
    fixture(&root);
    let manifest_path = root.join("Cargo.toml");
    let manifest = fs::read_to_string(&manifest_path).expect("root manifest");
    assert!(
        manifest.contains("members = [\"crates/*\"]"),
        "explicit member fixture changed"
    );
    let manifest = manifest
        .replace(
            "members = [\"crates/*\"]",
            "members = [\"crates/client\", \"crates/core-sdk\"]",
        )
        .replace("version = \"1.0.0\"", "version = \">=1.0.0\"");
    fs::write(&manifest_path, manifest).expect("set explicit members without selected core");
    let metadata = Command::new("cargo")
        .current_dir(&root)
        .args(["metadata", "--offline", "--no-deps", "--format-version", "1"])
        .output()
        .expect("read Cargo workspace metadata");
    assert!(
        metadata.status.success(),
        "invalid Cargo fixture: {}",
        String::from_utf8_lossy(&metadata.stderr)
    );
    let metadata: serde_json::Value = serde_json::from_slice(&metadata.stdout).expect("Cargo metadata JSON");
    let core = metadata["packages"]
        .as_array()
        .expect("packages")
        .iter()
        .find(|package| package["name"].as_str() == Some("scope-core"))
        .expect("Cargo resolves selected core package");
    assert!(
        metadata["workspace_members"]
            .as_array()
            .expect("workspace members")
            .contains(&core["id"]),
        "selected core must be a real implicit Cargo workspace member"
    );
    let helper_before = fs::read(root.join("crates/helper/Cargo.toml")).expect("unrelated helper");
    let output = Command::new(env!("CARGO_BIN_EXE_alef"))
        .current_dir(&root)
        .args(["generate", "--skip-compile"])
        .output()
        .expect("run generate");
    assert!(
        output.status.success(),
        "generate failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    let sdk = fs::read_to_string(root.join("crates/core-sdk/Cargo.toml")).expect("selected SDK");
    let sdk: toml::Value = toml::from_str(&sdk).expect("SDK TOML");
    assert_eq!(
        sdk["package"]["version"].as_str(),
        Some("2.0.0"),
        "implicit core SDK must reconcile"
    );
    let manifest = fs::read_to_string(manifest_path).expect("root manifest after");
    let manifest: toml::Value = toml::from_str(&manifest).expect("root TOML");
    assert_eq!(
        manifest["workspace"]["dependencies"]["core_alias"]["version"].as_str(),
        Some("2.0.0")
    );
    assert_eq!(
        fs::read(root.join("crates/helper/Cargo.toml")).expect("helper after"),
        helper_before
    );
}
